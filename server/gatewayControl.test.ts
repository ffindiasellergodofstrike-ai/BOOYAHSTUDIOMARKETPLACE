import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { Store } from './store';
import { assertGatewayForNewOrder, gatewayReadiness, getPublicGatewayConfig, registerGatewayControlRoutes } from './gatewayControl';

test('gateway settings are persisted, validate readiness, switch only new checkouts and never expose secrets', async t => {
  const savedEnv = { ...process.env }, originalGet = Store.get, originalMulti = Store.setMultiple;
  const data: Record<string, any> = {};
  Store.get = async (key: string) => data[key] || null;
  Store.setMultiple = async value => { Object.assign(data, value); };
  delete process.env.SUPABASE_URL; delete process.env.SUPABASE_SERVICE_ROLE_KEY;
  assert.equal((await getPublicGatewayConfig()).activeProvider, null);
  process.env.SUPABASE_URL = 'https://synthetic.supabase.co'; process.env.SUPABASE_SERVICE_ROLE_KEY = 'synthetic-service-secret';
  process.env.CASHFREE_APP_ID = 'synthetic-app'; process.env.CASHFREE_SECRET_KEY = 'synthetic-cashfree-secret'; process.env.CASHFREE_ENV = 'production';
  process.env.RAZORPAY_KEY_ID = 'rzp_live_synthetic'; process.env.RAZORPAY_KEY_SECRET = 'synthetic-razorpay-secret'; delete process.env.RAZORPAY_WEBHOOK_SECRET;
  assert.equal(gatewayReadiness('razorpay').configured, false);
  process.env.RAZORPAY_WEBHOOK_SECRET = 'synthetic-webhook-secret';
  const app = express(); app.use(express.json());
  const pass: any = (req: any, _res: any, next: any) => { req.userId = 'owner'; next(); };
  registerGatewayControlRoutes(app, pass, pass, pass);
  const server = app.listen(0, '127.0.0.1'); await new Promise<void>(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise<void>(resolve => server.close(() => resolve())); Store.get = originalGet; Store.setMultiple = originalMulti; for (const key of Object.keys(process.env)) if (!(key in savedEnv)) delete process.env[key]; Object.assign(process.env, savedEnv); });
  const url = `http://127.0.0.1:${(server.address() as any).port}/api/marketplace/admin/gateways`;
  const patch = (body: any) => fetch(url, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal((await getPublicGatewayConfig()).activeProvider, null);
  assert.equal((await patch({ enabled: { easebuzz: true }, reason: 'Enable checkout' })).status, 409);
  assert.equal((await patch({ enabled: { cashfree: true }, reason: 'Initial approved PG setup' })).status, 200);
  const cf = await getPublicGatewayConfig(); assert.equal(cf.activeProvider, 'cashfree');
  assert.equal(cf.gateways.cashfree.capabilities.marketplace, false);
  await assert.rejects(assertGatewayForNewOrder('cashfree', { paymentProvider: 'Razorpay' }));
  await assert.rejects(assertGatewayForNewOrder('cashfree', { marketplace: { sellerId: 'creator' } }));
  assert.equal((await patch({ enabled: { cashfree: false, razorpay: true }, defaultProvider: 'razorpay', commissionBps: 1200, reason: 'Switch future checkout to Razorpay' })).status, 200);
  assert.equal((await getPublicGatewayConfig()).activeProvider, 'razorpay');
  await assert.rejects(assertGatewayForNewOrder('cashfree'));
  await assertGatewayForNewOrder('razorpay', { paymentProvider: 'Razorpay', paymentEnvironment: 'live' });
  assert.equal((await patch({ credentials: { key: 'secret' }, reason: 'Do not accept credentials here' })).status, 400);
  assert.equal((await patch({ commissionBps: 5001, reason: 'Invalid commission' })).status, 400);
  const response = await (await fetch(url)).text();
  assert.equal(response.includes('synthetic-'), false);
  assert.equal(Object.keys(data).filter(key => key.startsWith('marketplace/audit/')).length, 2);
});
