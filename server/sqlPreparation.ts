import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** Explicit order only: do not glob historical SQL that can replace newer RPCs. */
export const UPGRADE_SETUP_FILES = [
  'supabase/migrations/202610240001_creator_pricing_limits.sql',
  'supabase/migrations/202610240002_plans.sql',
  'supabase/migrations/202610240003_settlements.sql',
  'supabase/migrations/202610240004_setup_readiness.sql',
  'supabase/migrations/202610240010_uploads.sql',
  'supabase/migrations/202610240011_creator_marketplace.sql',
] as const;
export const FRESH_SETUP_FILES = [
  'supabase/schema.sql',
  'supabase/migrations/202610230001_creator_marketplace.sql',
  'supabase/migrations/202610230003_easebuzz.sql',
  'supabase/migrations/202610230004_subscriptions.sql',
  ...UPGRADE_SETUP_FILES,
] as const;

export function renderMarketplaceSql(mode: 'fresh' | 'upgrade', projectRoot = process.cwd()): string {
  const files = mode === 'fresh' ? FRESH_SETUP_FILES : UPGRADE_SETUP_FILES;
  const notice = mode === 'fresh'
    ? 'FRESH PROJECT ONLY. Use a separate Supabase project. Do not replace an existing production store with a development snapshot.'
    : 'EXISTING MARKETPLACE UPGRADE ONLY. Back up the database; the baseline and the 20261023 marketplace migrations must already be present.';
  return [
    '-- Generated by pnpm setup:sql from an explicit migration manifest.',
    `-- ${notice}`,
    '-- Review the entire file, then apply the appropriate file in Supabase SQL Editor.',
    '-- This generator never connects to a database or executes SQL.',
    'begin;',
    ...files.map(file => `\n-- BEGIN FILE: ${file}\n${readFileSync(resolve(projectRoot, file), 'utf8').trimEnd()}\n-- END FILE: ${file}\n`),
    'commit;',
    '',
  ].join('\n');
}
